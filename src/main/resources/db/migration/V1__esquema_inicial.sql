
-- V1: esquema inicial de AgroSierra

CREATE TABLE lotes (
                       id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                       codigo VARCHAR2(30 CHAR) NOT NULL,
                       nombre VARCHAR2(100 CHAR) NOT NULL,
                       hectareas FLOAT(53) NOT NULL,
                       cultivo VARCHAR2(100 CHAR) NOT NULL,
                       valle VARCHAR2(100 CHAR) NOT NULL,
                       campania_cerrada BOOLEAN NOT NULL,
                       dosis_maxima_por_hectarea FLOAT(53) NOT NULL,

                       CONSTRAINT pk_lotes PRIMARY KEY (id),
                       CONSTRAINT uk_lotes_codigo UNIQUE (codigo),
                       CONSTRAINT ck_lotes_hectareas CHECK (hectareas > 0),
                       CONSTRAINT ck_lotes_dosis CHECK (dosis_maxima_por_hectarea > 0)
);

CREATE TABLE labores (
                         id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                         lote_id NUMBER(19,0) NOT NULL,
                         tipo VARCHAR2(30 CHAR) NOT NULL,
                         fecha DATE NOT NULL,
                         responsable VARCHAR2(150 CHAR) NOT NULL,
                         cantidad FLOAT(53),
                         observacion VARCHAR2(500 CHAR),
                         pendiente BOOLEAN NOT NULL,
                         usuario_id NUMBER(19,0) NOT NULL,
                         fecha_creacion TIMESTAMP(6) NOT NULL,
                         fecha_modificacion TIMESTAMP(6),

                         CONSTRAINT pk_labores PRIMARY KEY (id),
                         CONSTRAINT fk_labores_lote
                             FOREIGN KEY (lote_id) REFERENCES lotes(id),
                         CONSTRAINT ck_labores_tipo
                             CHECK (tipo IN ('RIEGO', 'FUMIGACION', 'COSECHA'))
);

CREATE INDEX ix_labores_lote_fecha
    ON labores (lote_id, fecha DESC, id DESC);
