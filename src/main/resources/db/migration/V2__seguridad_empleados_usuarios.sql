
-- V2: seguridad de AgroSierra

CREATE TABLE empleados (
                           id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                           dni VARCHAR2(8 CHAR) NOT NULL,
                           nombres VARCHAR2(100 CHAR) NOT NULL,
                           apellidos VARCHAR2(100 CHAR) NOT NULL,
                           cargo VARCHAR2(60 CHAR) NOT NULL,
                           email VARCHAR2(150 CHAR) NOT NULL,
                           telefono VARCHAR2(15 CHAR),
                           estado BOOLEAN NOT NULL,
                           fecha_creacion TIMESTAMP(6) NOT NULL,
                           fecha_modificacion TIMESTAMP(6),

                           CONSTRAINT pk_empleados PRIMARY KEY (id),
                           CONSTRAINT uk_empleados_dni UNIQUE (dni)
);

CREATE UNIQUE INDEX ux_empleados_email
    ON empleados (UPPER(email));

CREATE TABLE roles (
                       id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                       nombre VARCHAR2(30 CHAR) NOT NULL,
                       descripcion VARCHAR2(150 CHAR),

                       CONSTRAINT pk_roles PRIMARY KEY (id),
                       CONSTRAINT uk_roles_nombre UNIQUE (nombre)
);

CREATE TABLE usuarios (
                          id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                          username VARCHAR2(50 CHAR) NOT NULL,
                          password VARCHAR2(100 CHAR) NOT NULL,
                          estado BOOLEAN NOT NULL,
                          empleado_id NUMBER(19,0) NOT NULL,
                          fecha_creacion TIMESTAMP(6) NOT NULL,
                          fecha_modificacion TIMESTAMP(6),

                          CONSTRAINT pk_usuarios PRIMARY KEY (id),
                          CONSTRAINT uk_usuarios_empleado UNIQUE (empleado_id),
                          CONSTRAINT fk_usuarios_empleado
                              FOREIGN KEY (empleado_id) REFERENCES empleados(id)
);

CREATE UNIQUE INDEX ux_usuarios_username
    ON usuarios (UPPER(username));

CREATE TABLE usuario_roles (
                               usuario_id NUMBER(19,0) NOT NULL,
                               rol_id NUMBER(19,0) NOT NULL,

                               CONSTRAINT pk_usuario_roles PRIMARY KEY (usuario_id, rol_id),
                               CONSTRAINT fk_usuario_roles_usuario
                                   FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
                               CONSTRAINT fk_usuario_roles_rol
                                   FOREIGN KEY (rol_id) REFERENCES roles(id)
);

ALTER TABLE labores
    ADD CONSTRAINT fk_labores_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios(id);

